import assert from 'node:assert/strict';
import { boundedNumber, numericSettings, numericValue, settingsSections } from '../appearance.mjs';
assert.equal(settingsSections.find(section => section[0] === 'scrolling')[1], 'Scrolling');
assert.deepEqual(settingsSections.map(section => section[0]), ['0','1','scrolling','2','3','4','5'],'section keys stay stable');
const width = numericSettings.find(s => s.key === 'picker-width');
assert.equal(boundedNumber('537',width),537);
assert.equal(boundedNumber('',width),520);
assert.equal(boundedNumber('bad',width),520);
assert.equal(boundedNumber(Infinity,width),520);
assert.equal(boundedNumber(2000,width),1000);
assert.equal(boundedNumber(-10,width),320);
const prefs = { getBoolPref:()=>true, getIntPref:(key,fallback)=>fallback };
assert.equal(numericValue('item-spacing',prefs),5,'existing compact spacing is preserved');
prefs.getBoolPref=()=>false;
assert.equal(numericValue('item-spacing',prefs),8);
prefs.getIntPref=()=>537;
assert.equal(numericValue('picker-width',prefs),537,'intermediate values are not rounded to presets');
const edge = numericSettings.find(setting=>setting.key==='accordion-border-width');
assert.equal(boundedNumber(0,edge),0,'accordion separation can be disabled');
assert.equal(boundedNumber(100,edge),8,'edge thickness is bounded');
assert.equal(boundedNumber('bad',edge),0,'invalid edge thickness falls back to shadow-only');
console.log('Appearance value tests passed.');

const {conditionMatches}=await import('../appearance.mjs');
const definitions=[{property:'enabled',defaultValue:true},{property:'preset',defaultValue:4}];
const defaults={getBoolPref:(key,fallback)=>fallback,getIntPref:(key,fallback)=>fallback};
assert.equal(conditionMatches(defaults,{property:'enabled',value:true},definitions),true,'unregistered boolean uses schema default');
assert.equal(conditionMatches(defaults,{property:'preset',value:4},definitions),true,'unregistered integer uses schema default');
assert.equal(conditionMatches({...defaults,getBoolPref:()=>false},{property:'enabled',value:true},definitions),false,'user override controls visibility');
